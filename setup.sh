// ============================================================
// Vercel Serverless Function - Contact Form Mail Sender
// Route: POST /api/contact
// ============================================================

const nodemailer = require('nodemailer');

// Simple in-memory rate limit (per instance)
const rateLimit = new Map();
const RATE_LIMIT_WINDOW = 60 * 1000; // 1 minute
const RATE_LIMIT_MAX = 5; // max 5 requests per minute per IP

function isRateLimited(ip) {
  const now = Date.now();
  const record = rateLimit.get(ip) || { count: 0, start: now };
  if (now - record.start > RATE_LIMIT_WINDOW) {
    record.count = 0;
    record.start = now;
  }
  record.count++;
  rateLimit.set(ip, record);
  return record.count > RATE_LIMIT_MAX;
}

function cleanInput(val) {
  if (typeof val !== 'string') return '';
  return val.trim().replace(/[\r\n]+/g, ' ').slice(0, 2000);
}

function isValidEmail(email) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
}

module.exports = async (req, res) => {
  // CORS headers
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  // Rate limit check
  const ip = req.headers['x-forwarded-for']?.split(',')[0] || req.socket?.remoteAddress || 'unknown';
  if (isRateLimited(ip)) {
    return res.status(429).json({ error: 'Too many requests. Please wait a minute.' });
  }

  try {
    const body = typeof req.body === 'string' ? JSON.parse(req.body) : req.body;

    const name    = cleanInput(body.name);
    const email   = cleanInput(body.email);
    const phone   = cleanInput(body.phone);
    const subject = cleanInput(body.subject);
    const message = typeof body.message === 'string' ? body.message.trim().slice(0, 5000) : '';

    // Validation
    const errors = [];
    if (!name) errors.push('Name is required');
    if (!email) errors.push('Email is required');
    if (email && !isValidEmail(email)) errors.push('Invalid email');
    if (!message) errors.push('Message is required');

    if (errors.length > 0) {
      return res.status(400).json({ error: errors.join(', ') });
    }

    // SMTP transporter
    const transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST || 'smtp.gmail.com',
      port: parseInt(process.env.SMTP_PORT || '587'),
      secure: parseInt(process.env.SMTP_PORT || '587') === 465,
      auth: {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS,
      },
    });

    const htmlBody = `
      <div style="font-family: Arial, sans-serif; max-width: 600px; color: #333;">
        <h2 style="color: #2563eb; border-bottom: 2px solid #2563eb; padding-bottom: 8px;">
          New Website Inquiry
        </h2>
        <table cellpadding="8" style="border-collapse: collapse; width: 100%;">
          <tr><td style="width: 100px;"><strong>Name:</strong></td><td>${escapeHtml(name)}</td></tr>
          <tr><td><strong>Email:</strong></td><td><a href="mailto:${escapeHtml(email)}">${escapeHtml(email)}</a></td></tr>
          <tr><td><strong>Phone:</strong></td><td>${escapeHtml(phone) || '-'}</td></tr>
          <tr><td><strong>Subject:</strong></td><td>${escapeHtml(subject) || '-'}</td></tr>
        </table>
        <h3 style="margin-top: 24px;">Message:</h3>
        <div style="background: #f3f4f6; padding: 16px; border-radius: 8px; white-space: pre-wrap;">${escapeHtml(message)}</div>
        <hr style="margin-top: 24px; border: none; border-top: 1px solid #e5e7eb;">
        <p style="color: #6b7280; font-size: 12px;">
          Received on ${new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })}
        </p>
      </div>
    `;

    const textBody = `New Inquiry\n\nName: ${name}\nEmail: ${email}\nPhone: ${phone}\nSubject: ${subject}\n\nMessage:\n${message}`;

    await transporter.sendMail({
      from: `"Website Contact" <${process.env.SMTP_USER}>`,
      to: process.env.MAIL_TO || 'support@shayconsultancy.in',
      replyTo: email,
      subject: `New Inquiry from ${name}${subject ? ' - ' + subject : ''}`,
      text: textBody,
      html: htmlBody,
    });

    return res.status(200).json({ success: true, message: 'Email sent successfully' });

  } catch (err) {
    console.error('Mail error:', err);
    return res.status(500).json({ error: 'Failed to send email. Please try again.' });
  }
};

function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
