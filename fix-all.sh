# STEP 2: Kaunsi Files supabase.js Se Import Kar Rahi Hain
# ============================================================
header "Step 2: Finding ALL Imports from supabase.js"

# Saari files dhundho jo supabase se import kar rahi hain
IMPORT_FILES=$(find src -type f \( -name "*.js" -o -name "*.jsx" -o -name "*.ts" -o -name "*.tsx" \) 2>/dev/null | xargs grep -l "from.*supabase" 2>/dev/null || true)

ALL_IMPORTS=""

if [ -z "$IMPORT_FILES" ]; then
    warn "Koi file supabase.js se import nahi kar rahi"
else
    echo "$IMPORT_FILES" | while read -r file; do
        echo -e "${CYAN}📄 $file${NC}"
        
        # Extract import statements
        grep -E "import.*from.*supabase" "$file" | while read -r line; do
            echo "   $line"
        done
        echo ""
    done
    
    # Collect all imported names
    echo "$IMPORT_FILES" | while read -r file; do
        # Match: import { x, y, z } from '.../supabase'
        NAMES=$(grep -oE "import\s*\{[^}]+\}\s*from\s*['\"].*supabase" "$file" 2>/dev/null | \
            sed 's/import\s*{//' | sed 's/}.*//' | tr ',' '\n' | sed 's/^[[:space:]]*//' | sed 's/[[:space:]]*$//' | sort -u)
        if [ -n "$NAMES" ]; then
            ALL_IMPORTS="$ALL_IMPORTS$NAMES"$'\n'
        fi
        
        # Match default imports: import supabase from '.../supabase'
        if grep -qE "import\s+[a-zA-Z_]+\s+from\s*['\"].*supabase['\"]" "$file" 2>/dev/null; then
            ALL_IMPORTS="$ALL_IMPORTS"$'supabase (default)\n'
        fi
    done
fi

# Unique sort
ALL_IMPORTS=$(echo "$ALL_IMPORTS" | sort -u | grep -v '^$' || true)

header "Step 3: All Imported Names (Consolidated)"

if [ -z "$ALL_IMPORTS" ]; then
    warn "Koi import nahi mila"
else
    echo "$ALL_IMPORTS" | while read -r name; do
        [ -n "$name" ] && echo "   • $name"
    done
fi
