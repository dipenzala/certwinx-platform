const nodemailer = require('nodemailer');

module.exports = async (req, res) => {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  try {
    const body = typeof req.body === 'string' ? JSON.parse(req.body) : req.body;
    const clean = (s) => (typeof s === 'string' ? s.trim().slice(0, 2000) : '');
    
    const name    = clean(body.name);
    const email   = clean(body.email);
    const phone   = clean(body.phone);
    const subject = clean(body.subject);
    const message = clean(body.message);

    if (!name || !email || !message) {
      return res.status(400).json({ error: 'Name, email and message required' });
    }

    const transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST || 'smtp.gmail.com',
      port: parseInt(process.env.SMTP_PORT || '587'),
      secure: parseInt(process.env.SMTP_PORT || '587') === 465,
      auth: { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS },
    });

    const esc = (s) => String(s).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

    await transporter.sendMail({
      from: `"Website Contact" <${process.env.SMTP_USER}>`,
      to: process.env.MAIL_TO || 'support@shayconsultancy.in',
      replyTo: email,
      subject: `New Inquiry from ${name}${subject ? ' - ' + subject : ''}`,
      text: `Name: ${name}\nEmail: ${email}\nPhone: ${phone}\nSubject: ${subject}\n\n${message}`,
      html: `<div style="font-family:Arial;max-width:600px">
        <h2 style="color:#2563eb">New Website Inquiry</h2>
        <p><b>Name:</b> ${esc(name)}<br>
        <b>Email:</b> ${esc(email)}<br>
        <b>Phone:</b> ${esc(phone)}<br>
        <b>Subject:</b> ${esc(subject)}</p>
