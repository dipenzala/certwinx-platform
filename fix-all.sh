// ⭐ AUTH FUNCTIONS (for Admin.jsx, Login, etc.)
// ============================================================
export async function signIn(email, password) {
  console.log('🔐 Sign in attempt:', email);
  
  // Simple hardcoded auth for admin (change as needed)
  const ADMIN_EMAIL = import.meta.env.VITE_ADMIN_EMAIL || 'admin@shayconsultancy.in';
  const ADMIN_PASS  = import.meta.env.VITE_ADMIN_PASS  || 'admin123';
  
  if (email === ADMIN_EMAIL && password === ADMIN_PASS) {
    const session = { user: { email, role: 'admin' }, expires: Date.now() + 86400000 };
    localStorage.setItem('admin_session', JSON.stringify(session));
    return { success: true, data: session };
  }
  
  return { success: false, error: 'Invalid credentials' };
}

export async function signOut() {
  console.log('🔓 Sign out');
  localStorage.removeItem('admin_session');
  return { success: true };
}

export async function getSession() {
  try {
    const raw = localStorage.getItem('admin_session');
    if (!raw) return { success: false, session: null };
    const session = JSON.parse(raw);
    if (session.expires && session.expires < Date.now()) {
      localStorage.removeItem('admin_session');
      return { success: false, session: null };
    }
    return { success: true, session };
  } catch {
    return { success: false, session: null };
  }
}

export async function getCurrentUser() {
  const { session } = await getSession();
  return session?.user || null;
}

